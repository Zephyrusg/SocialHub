from starlette.responses import HTMLResponse, RedirectResponse
from app.core import HubError
from app.security.origins import browser_request
from app.services.meta_oauth import MetaOAuth

HEADERS = {'Cache-Control': 'no-store', 'Pragma': 'no-cache', 'Referrer-Policy': 'no-referrer',
           'Content-Security-Policy': "default-src 'none'; frame-ancestors 'none'; base-uri 'none'",
           'X-Content-Type-Options': 'nosniff'}
COOKIE = '__Secure-socialhub-meta'


def register_meta_routes(mcp, settings, sessions):
    service = MetaOAuth(settings, sessions)

    def trusted_https(request):
        # This header is overwritten, never passed through, by the dedicated loopback TLS vhost.
        return browser_request(request, settings)

    @mcp.custom_route('/meta/oauth/start', methods=['GET'])
    async def start(request):
        if not trusted_https(request):
            return HTMLResponse('Use the configured HTTPS login link generated by scripts/meta_login.py.', status_code=403, headers=HEADERS)
        try:
            if len(request.query_params.getlist('ticket')) != 1:
                raise HubError('invalid_oauth_flow', 'One login ticket is required')
            url, browser = service.start(request.query_params.get('ticket'))
            response = RedirectResponse(url, status_code=303, headers=HEADERS)
            response.set_cookie(COOKIE, browser, max_age=600, path='/meta/oauth', secure=True, httponly=True, samesite='lax')
            return response
        except HubError as error:
            return HTMLResponse(error.code + ': Start a new login using scripts/meta_login.py.', status_code=400, headers=HEADERS)

    @mcp.custom_route('/meta/oauth/callback', methods=['GET'])
    async def callback(request):
        if not trusted_https(request):
            return HTMLResponse('Trusted HTTPS callback required.', status_code=403, headers=HEADERS)
        try:
            if len(request.query_params.getlist('state')) != 1 or len(request.query_params.getlist('code')) > 1:
                raise HubError('invalid_oauth_state', 'Invalid callback parameters')
            result = await service.complete(request.query_params.get('state'), request.cookies.get(COOKIE),
                request.query_params.get('code'), denied='error' in request.query_params)
            response = HTMLResponse('PixelPapa Facebook and Instagram accounts verified and connected. Live writes remain disabled. You may close this window.', headers=HEADERS)
        except HubError as error:
            service_log(sessions, error.code, error.stage, error.diagnostics)
            response = HTMLResponse(error.code + (' at ' + error.stage if error.stage else '') + ': Connection failed. Use the local CLI verification command for safe diagnostics and start a new login.', status_code=400, headers=HEADERS)
        except Exception:
            service_log(sessions, 'internal_error')
            response = HTMLResponse('Connection failed. No tokens are displayed. Check local service readiness and start a new login.', status_code=500, headers=HEADERS)
        response.delete_cookie(COOKIE, path='/meta/oauth', secure=True, httponly=True, samesite='lax')
        return response


def service_log(sessions, code, stage=None, diagnostics=None):
    from app.database.models import Audit
    with sessions.begin() as db:
        db.add(Audit(subject='local-meta-owner', operation='meta_connect', outcome='error', details={'code': code, **({'stage': stage} if stage else {}), **(diagnostics or {})}))
