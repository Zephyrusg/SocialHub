from typing import Protocol


class Connector(Protocol):
    platform: str
    def capabilities(self, account_type: str) -> dict: ...
    async def list_posts(self, remote_id: str, limit: int, cursor: str | None) -> dict: ...
    async def get_post(self, remote_id: str, post_id: str) -> dict: ...
    async def list_comments(self, remote_id: str, post_id: str, limit: int, cursor: str | None) -> dict: ...
